"""Streaming LLM client and internal thought-tag filtering.

This module coordinates:
1. `ThinkStripper`: A stateful text stream processor that filters out internal
   `<think>...</think>` tags generated by reasoning models (such as DeepSeek-R1 or Qwen3),
   preventing "thinking aloud" tokens from leaking into end-user UI or TTS outputs.
2. `StreamStats`: Performance telemetry tracking time-to-first-token (TTFT),
   total generation time, token counts, and overall tokens per second (tok/s).
3. `LLMClient`: Asynchronous wrapper around `openai.AsyncOpenAI` pointing to
   local endpoints (such as Ollama or vLLM) with streaming support.

Example:
    ```python
    import asyncio
    from jarvis.llm import LLMClient, StreamStats

    async def main():
        client = LLMClient()
        stats = StreamStats()
        messages = [
            {"role": "system", "content": "You are helpful."},
            {"role": "user", "content": "What is gravity?"}
        ]
        async for chunk in client.stream(messages, stats=stats):
            print(chunk, end="", flush=True)
        print(f"\\nStats: {stats.summary()}")

    asyncio.run(main())
    ```
"""

import time
from dataclasses import dataclass
from typing import AsyncIterator, Literal

from openai import AsyncOpenAI

from jarvis.config import settings


class ThinkStripper:
    """Removes `<think>...</think>` sections from a token stream in real-time.

    Reasoning models emit reasoning inside `<think>` tags. When streaming output chunk by chunk,
    a tag might be split across multiple chunks (e.g., chunk 1: `</thi`, chunk 2: `nk>`).
    This class maintains an internal buffer and state machine to safely detect and suppress
    thoughts without buffering the entire output.

    Example:
        >>> stripper = ThinkStripper()
        >>> stripper.feed("Hello <think>thinking process</think>world!")
        'Hello world!'
        >>> stripper.flush()
        ''
    """

    OPEN, CLOSE = "<think>", "</think>"

    def __init__(self) -> None:
        self.buf = ""
        self.inside = False

    def feed(self, text: str) -> str:
        """Feed a new chunk of streamed text and return printable text with thinking tags stripped.

        Args:
            text: Incoming text chunk from the LLM stream.

        Returns:
            The sanitized text ready for display or TTS.
        """
        self.buf += text
        out: list[str] = []
        while True:
            tag = self.CLOSE if self.inside else self.OPEN
            i = self.buf.find(tag)
            if i != -1:
                # Found the complete delimiter
                if not self.inside:
                    out.append(self.buf[:i])
                self.buf = self.buf[i + len(tag) :]
                self.inside = not self.inside
                continue

            # No complete tag: check if the buffer suffix matches the beginning of a tag
            # (e.g. buffer ends with "<th" which could become "<think>")
            keep = 0
            for k in range(min(len(tag) - 1, len(self.buf)), 0, -1):
                if tag.startswith(self.buf[-k:]):
                    keep = k
                    break
            cut = len(self.buf) - keep
            if not self.inside:
                out.append(self.buf[:cut])
            self.buf = self.buf[cut:]
            break
        return "".join(out)

    def flush(self) -> str:
        """Flush remaining buffered text once generation finishes.

        Returns:
            Any remaining text that was not inside a `<think>` block.
        """
        rest = "" if self.inside else self.buf
        self.buf = ""
        return rest


@dataclass
class StreamStats:
    """Metrics collector for LLM streaming completions.

    Attributes:
        first_token_s: Time elapsed in seconds until the first printable token arrived (TTFT).
        total_s: Total time elapsed during the entire generation process.
        chunks: Number of text chunks yielded during generation.
        completion_tokens: Actual token count reported by provider usage metadata (if available).
    """

    first_token_s: float | None = None
    total_s: float = 0.0
    chunks: int = 0
    completion_tokens: int | None = None

    def summary(self) -> str:
        """Produce a formatted human-readable summary of streaming performance.

        Returns:
            String with time-to-first-token, token count, and speed in tokens/second.

        Example:
            >>> stats = StreamStats(first_token_s=0.45, total_s=2.0, chunks=40)
            >>> stats.summary()
            'first token 0.5s | 40 tokens | 20.0 tok/s overall'
        """
        n = self.completion_tokens or self.chunks
        tps = n / self.total_s if self.total_s > 0 and n else 0.0
        first = f"{self.first_token_s:.1f}s" if self.first_token_s is not None else "n/a"
        return f"first token {first} | {n} tokens | {tps:.1f} tok/s overall"


class LLMClient:
    """Asynchronous client for interacting with OpenAI-compatible LLM servers (Ollama, vLLM, etc.)."""

    def __init__(self) -> None:
        """Initialize the underlying AsyncOpenAI client with settings from config."""
        self._client = AsyncOpenAI(
            base_url=settings.llm_base_url,
            api_key=settings.llm_api_key,
            timeout=settings.llm_timeout_s,
            max_retries=0,
        )

    @staticmethod
    def model_for(tier: Literal["fast", "smart"]) -> str:
        """Map a model tier name to its configured model identifier.

        Args:
            tier: 'fast' (latency-optimized) or 'smart' (reasoning-optimized).

        Returns:
            The configured model string from Settings.
        """
        return settings.fast_model if tier == "fast" else settings.smart_model

    @staticmethod
    def _prepare(messages: list[dict], model: str, think: bool) -> list[dict]:
        """Copy messages and apply model-specific flags or prompt modifications.

        For example, Qwen3 models support `/no_think` appended to the user prompt
        to bypass chain-of-thought generation and save latency.

        Args:
            messages: Input list of message dictionaries.
            model: Model name string.
            think: Whether to allow the model to produce reasoning tokens.

        Returns:
            A clean shallow-copy of messages with any necessary model-specific directives.
        """
        msgs = [dict(m) for m in messages]
        return msgs

    async def stream(
        self,
        messages: list[dict],
        tier: Literal["fast", "smart"] = "fast",
        think: bool = False,
        stats: StreamStats | None = None,
        tools: list[dict] | None = None,
    ) -> AsyncIterator[dict]:
        """Stream generated response tokens and tool calls asynchronously.

        Args:
            messages: List of chat messages (`[{"role": "...", "content": "..."}]`).
            tier: 'fast' or 'smart' model selection.
            think: If True, keep thinking tags; if False, filter out `<think>` blocks.
            stats: Optional StreamStats instance to record latency and throughput.
            tools: Optional OpenAI-format tools schema list.

        Yields:
            Dict events:
            - `{"type": "token", "content": str}`
            - `{"type": "tool_call", "name": str, "arguments": str, "id": str}`
        """
        model = self.model_for(tier)
        stats = stats if stats is not None else StreamStats()
        stripper = ThinkStripper()
        started = False
        t0 = time.perf_counter()
        tool_call_acc: dict[int, dict] = {}

        kwargs = {
            "model": model,
            "messages": self._prepare(messages, model, think),
            "stream": True,
            "stream_options": {"include_usage": True},
        }
        if tools:
            kwargs["tools"] = tools

        try:
            resp = await self._client.chat.completions.create(**kwargs)
            async for chunk in resp:
                if chunk.usage:
                    stats.completion_tokens = chunk.usage.completion_tokens
                if not chunk.choices:
                    continue

                delta = chunk.choices[0].delta

                # Accumulate streaming tool calls
                if delta.tool_calls:
                    for tc in delta.tool_calls:
                        idx = tc.index
                        if idx not in tool_call_acc:
                            tool_call_acc[idx] = {
                                "id": tc.id or f"call_{idx}",
                                "name": tc.function.name or "",
                                "arguments": "",
                            }
                        if tc.function.name:
                            tool_call_acc[idx]["name"] = tc.function.name
                        if tc.function.arguments:
                            tool_call_acc[idx]["arguments"] += tc.function.arguments

                # Process text stream tokens
                content = delta.content or ""
                if content:
                    piece = stripper.feed(content)
                    if not started:
                        piece = piece.lstrip()
                    if piece:
                        if not started:
                            started = True
                            stats.first_token_s = time.perf_counter() - t0
                        stats.chunks += 1
                        yield {"type": "token", "content": piece}

            tail = stripper.flush()
            tail = tail if started else tail.lstrip()
            if tail:
                yield {"type": "token", "content": tail}

            # Emit accumulated tool calls if any were detected
            for call in tool_call_acc.values():
                yield {"type": "tool_call", **call}

        finally:
            stats.total_s = time.perf_counter() - t0
